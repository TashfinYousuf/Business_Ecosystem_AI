"""
backend/aegis-sentinel/firewall.py
Deterministic Sentinel Firewall for LLM Ingestion & Action Guarding.
Inspects payloads for prompt injections, system leaks, and financial tampering.
"""

from __future__ import annotations

import json
import logging
import os
import re
from dataclasses import dataclass
from typing import Any, Dict, List, Optional

from .kill_switch import KillSwitchManager, CircuitBreakerOpenException

logger = logging.getLogger("AegisFirewall")


@dataclass
class InspectionResult:
    is_safe: bool
    risk_level: str  # "LOW", "MEDIUM", "CRITICAL"
    reason: Optional[str] = None
    sanitized_content: Optional[str] = None


class AegisSentinelFirewall:
    def __init__(self, rules_path: Optional[str] = None, kill_switch: Optional[KillSwitchManager] = None):
        base_dir = os.path.dirname(__file__)
        self.rules_path = rules_path or os.path.join(base_dir, "rules.json")
        self.kill_switch = kill_switch or KillSwitchManager()
        self.rules = self._load_rules()

        # Compile regular expressions
        self.blocked_patterns = [
            re.compile(p) for p in self.rules.get("blocked_instruction_patterns", [])
        ]
        self.financial_patterns = [
            re.compile(p) for p in self.rules.get("financial_tamper_patterns", [])
        ]

    def _load_rules(self) -> Dict[str, Any]:
        """Loads sentinel threat patterns from JSON rules file."""
        try:
            with open(self.rules_path, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception as e:
            logger.error("Failed to load sentinel rules file: %s. Using safe defaults.", str(e))
            return {
                "blocked_instruction_patterns": [],
                "financial_tamper_patterns": []
            }

    def inspect_inbound_prompt(self, org_id: str, raw_text: str) -> InspectionResult:
        """
        Inspects incoming prompt/memo/OCR text before LLM consumption.
        Verifies circuit breakers and scans for injection payloads.
        """
        # Step 1: Check circuit breakers and kill switches
        try:
            self.kill_switch.verify_execution_permitted(org_id)
        except CircuitBreakerOpenException as cbe:
            return InspectionResult(
                is_safe=False,
                risk_level="CRITICAL",
                reason=str(cbe)
            )

        # Step 2: Instruction Injection Regex Matching
        for pattern in self.blocked_patterns:
            if pattern.search(raw_text):
                matched = pattern.pattern
                self.kill_switch.record_failure(org_id, f"Inbound injection attempt: {matched}")
                return InspectionResult(
                    is_safe=False,
                    risk_level="CRITICAL",
                    reason=f"Malicious prompt injection pattern detected: {matched}"
                )

        # Step 3: Financial Tampering Heuristics
        for pattern in self.financial_patterns:
            if pattern.search(raw_text):
                matched = pattern.pattern
                self.kill_switch.record_failure(org_id, f"Financial tampering pattern: {matched}")
                return InspectionResult(
                    is_safe=False,
                    risk_level="CRITICAL",
                    reason=f"Unauthorized financial mutation pattern detected: {matched}"
                )

        # Step 4: Neutralize control delimiters (Markdown fence injection escapes)
        sanitized = raw_text.replace("```system", "'''system").replace("```prompt", "'''prompt")

        return InspectionResult(
            is_safe=True,
            risk_level="LOW",
            sanitized_content=sanitized
        )

    def guard_outbound_action(self, org_id: str, action_name: str, parameters: Dict[str, Any]) -> InspectionResult:
        """
        Guards outbound autonomous tool execution generated by AI models.
        Blocks destructive mutations unless passed through a human approval gate.
        """
        # Strictly block direct balance overrides or destructive actions without human gate
        restricted_actions = ["delete_customer", "wipe_balance", "zero_due_amount", "drop_table"]
        
        if action_name.lower() in restricted_actions:
            self.kill_switch.record_failure(org_id, f"Restricted tool invocation attempted: {action_name}")
            return InspectionResult(
                is_safe=False,
                risk_level="CRITICAL",
                reason=f"Action '{action_name}' violates autonomous policy and requires Human Approval Gate."
            )

        # Parameter checks (e.g. negative prices, impossible invoice totals)
        if "amount" in parameters:
            try:
                amt = float(parameters["amount"])
                if amt < 0:
                    return InspectionResult(
                        is_safe=False,
                        risk_level="CRITICAL",
                        reason=f"Negative financial amount ({amt}) is not permitted."
                    )
            except (ValueError, TypeError):
                pass

        self.kill_switch.record_success(org_id)
        return InspectionResult(is_safe=True, risk_level="LOW")